def construct45degreeangle():
    print("45° Angle Construction Using Perpendicular Lines")
    print("\nSteps:")
    print("1. Draw a straight line AB.")
    print("2. At point A, construct a perpendicular line AC.")
    print("3. The angle BAC is 90°.")
    print("4. Bisect the 90° angle using a compass.")
    print("5. The bisector divides 90° into two equal angles.")

    original_angle = 90
    bisected_angle = original_angle / 2

    print("\nPerpendicular Angle:", original_angle, "°")
    print("After Bisecting:", bisected_angle, "°")
    print("Required angle constructed: 45°")

construct45degreeangle()