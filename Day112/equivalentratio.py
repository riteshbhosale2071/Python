def equivalentratio():
    first = int(input("Enter the first number of the ratio: "))
    second = int(input("Enter the second number of the ratio: "))
    multiplier = int(input("Enter the multiplier: "))

    print("Original Ratio:", first, ":", second)
    print("Equivalent Ratio:", first * multiplier, ":", second * multiplier)

equivalentratio()